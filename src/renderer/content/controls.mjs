function menuEntries() {
  return Object.fromEntries(MENU_HELP.map(([key, label, short]) => [`menu-${key}`, control(`menu-${key}`, `${label} menu`, {
    short,
    purpose: `${short} The items are shown as the PC•MACs manual photographs them (January 13, 2021 edition, pp. 133–134). Items the trainer simulates work; the others explain that they are not simulated.`,
    when: 'To find a command, or to see what PC•MACs offers.',
    example: label === 'RealTime' ? 'RealTime ▸ Show Main Controls brings up the Control Window.' : label === 'Edit' ? 'Edit ▸ Set Digitals On (Ctrl+1) turns the selected stretch of a digital ON.' : `Click ${label} to look inside; Esc closes it.`,
    mistakes: 'Assuming a menu item you can see is simulated; the trainer says when it is not.',
    expected: 'The menu opens under its name; greyed items are greyed in the manual too.',
    effect: 'Simulated items act on the trainer’s windows; nothing is sent anywhere.',
    mechanism: { text: SIM_NOTE, evidence: 'manual' },
    evidence: 'manual',
    cites: ['pcmacs-menus'],
  })]));
}

